// One line per argument: name, type, required, description.
function typeOf(s: JsonSchema | undefined): string {
  if (!s) return 'any';
  if (s.enum) return s.enum.map((v: unknown) => (v === null ? 'null' : `"${v}"`)).join(' \\| ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (s.type === 'object' && s.properties?.x && s.properties?.y && Object.keys(s.properties).length === 2) return '{x, y}';
  if (s.type === 'object' && s.properties) return `{${Object.keys(s.properties).join(', ')}}`;
  let t = s.type || 'any';
  const range = [];
  if (s.minimum !== undefined) range.push(`≥ ${s.minimum}`);
  if (s.exclusiveMinimum !== undefined) range.push(`> ${s.exclusiveMinimum}`);
  if (s.maximum !== undefined) range.push(`≤ ${s.maximum}`);
  if (range.length) t += ` (${range.join(', ')})`;
  return t;
}

const esc = (text: unknown) => String(text || '').replaceAll('|', '\\|').replaceAll('\n', ' ');

function argsTable(schema: JsonSchema = {}): string {
  const props = Object.entries(schema.properties || {});
  if (!props.length) return '_No arguments._\n';
  const req = new Set<string>(schema.required || []);
  return [
    '| Argument | Type | Required | Description |',
    '| --- | --- | --- | --- |',
    ...props.map(([k, s]) => `| \`${k}\` | ${esc(typeOf(s))} | ${req.has(k) ? 'yes' : ''} | ${esc(s.description)} |`),
    '',
  ].join('\n');
}

function section(name: string, spec: ActionSpec, extra = ''): string {
  return `### \`${name}\`\n\n${esc(spec.description)}${spec.mutates ? ' _Changes the project; undoable._' : ''}${extra}\n\n${argsTable(spec.args)}`;
}

