// Generate docs/agent.md from the agent's own definitions (action schemas,
// runner tools, limits and system prompt), so the reference cannot drift
// from the code. scripts/agent-docs.test.ts fails when the file is stale.
//
//   npm run docs
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { DECISION_LLM_ACTIONS, DECISION_TOOLS, DEFAULT_DECISION_MODEL } from '../src/agent/decide.ts';
import { DEFAULT_LLM, LLM_ACTIONS, RUNNER_TOOLS } from '../src/agent/llm.ts';
import { AGENT_ACTIONS } from '../src/agent/schema.ts';
import type { ActionSpec, JsonSchema } from '../src/types/index.ts';

// One line per argument: name, type, required, description.
function typeOf(s: JsonSchema | undefined): string {
  if (!s) return 'any';
  if (s.enum) return s.enum.map((v: unknown) => (v === null ? 'null' : `"${v}"`)).join(' \\| ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (s.type === 'object' && s.properties?.x && s.properties?.y && Object.keys(s.properties).length === 2)
    return '{x, y}';
  if (s.type === 'object' && s.properties) return `{${Object.keys(s.properties).join(', ')}}`;
  let t = s.type || 'any';
  const range = [];
  if (s.minimum !== undefined) range.push(`≥ ${s.minimum}`);
  if (s.exclusiveMinimum !== undefined) range.push(`> ${s.exclusiveMinimum}`);
  if (s.maximum !== undefined) range.push(`≤ ${s.maximum}`);
  if (range.length) t += ` (${range.join(', ')})`;
  return t;
}

const esc = (text: unknown) =>
  String(text || '')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ');

function argsList(schema: JsonSchema = {}): string {
  const props = Object.entries(schema.properties || {}).filter(([k]) => k !== 'panelId');
  if (!props.length) return '';
  const req = new Set<string>(schema.required || []);
  return `${props
    .map(([k, s]) => {
      const desc = esc(s.description);
      return `- \`${k}\`${req.has(k) ? '*' : ''} ${esc(typeOf(s))}${desc ? `: ${desc}` : ''}`;
    })
    .join('\n')}\n`;
}

function section(name: string, spec: ActionSpec, extra = ''): string {
  return `### \`${name}\`\n${esc(spec.description)}${spec.mutates ? ' _Mutates._' : ''}${extra}\n${argsList(spec.args)}`;
}

const groups: [string, string[]][] = [
  ['Reading', ['get_state', 'get_results', 'get_questions', 'sample_pixel', 'focus']],
  [
    'File, tool and page',
    ['open_url', 'set_tool', 'go_to_page', 'select_panel', 'add_panel', 'rename_panel', 'remove_panel'],
  ],
  ['Grid', ['set_grid', 'detect_grid_size', 'set_grid_size', 'set_labels', 'remove_grid']],
  [
    'Colorbar and matching',
    ['set_colorbar', 'add_tick', 'set_tick_value', 'remove_tick', 'set_colorbar_scale', 'set_settings'],
  ],
  ['ROI regions', ['add_region', 'remove_region', 'set_scale_bar']],
  ['Decisions and review', ['answer_question', 'set_review']],
  ['History and export', ['undo', 'redo', 'export_project']],
];
const listed = new Set(groups.flatMap(([, names]) => names));
const missing = Object.keys(AGENT_ACTIONS).filter((n) => !listed.has(n));
if (missing.length) throw new Error(`Add these actions to a group in scripts/agent-docs.ts: ${missing.join(', ')}`);

const llmOnly = (n: string) => (LLM_ACTIONS.includes(n) ? ' _LLM._' : '');

const md = `<!-- Generated by scripts/agent-docs.ts from the agent's definitions; do not edit by hand. -->
# Colormeris agent reference

Prompts, limits, caching and design notes live in the code and CLAUDE.md: [prompts](../src/agent/llm.ts) ([decision mode](../src/agent/decide/prompt.ts)), [schemas](../src/agent/schema.ts), [runner](../src/agent/runner.ts).

\`window.colormeris\` ([api.ts](../src/agent/api.ts)): \`await colormeris.run(name, args)\` validates against the JSON Schema, never throws, returns \`{ok, result, state?, notes?}\` or \`{ok: false, error}\`. \`batch([{name, args}])\` stops at the first failure; \`tools()\` lists schemas; \`log()\` returns the action and decision logs. Coordinates are page pixels. \`panelId\` (optional, default: active panel) is accepted by panel actions. * = required. _LLM._ = also a tool of the heatmap agent's LLM.

${groups.map(([title, names]) => `## ${title}\n\n${names.map((n) => section(n, AGENT_ACTIONS[n], llmOnly(n))).join('\n')}`).join('\n')}
## Typed questions

\`get_questions\` lists decisions (\`id\`, \`type\`, \`panelId\`, \`prompt\`, \`evidence\`, \`answerSchema\`); \`answer_question\` answers with \`confidence\` and \`source\`. Answers below \`policy.minConfidence\` (${'0.9'}) are escalated, not applied; \`source: "human"\` always applies.

- \`confirm_grid_size\` → \`{rows, cols}\`
- \`classify_flagged\` (≤ 3 flagged cells) → \`keep\` | \`exclude\` | \`recheck_colorbar\`
- \`classify_flagged_cells\` (> 3) → \`keep_all\` | \`exclude_all\` | \`recheck_colorbar\`
- \`confirm_tick_order\` → \`as_placed\` | \`fix_needed\`
- \`confirm_extraction\` → \`accept\` | \`reject\` (sets \`panel.review\`; goes \`stale\` when values change)

## Runner tools (agent only mode)

${Object.entries(RUNNER_TOOLS)
  .map(([n, t]) => section(n, t))
  .join('\n')}
## Decision-mode tools (LLM actions: ${DECISION_LLM_ACTIONS.map((n) => `\`${n}\``).join(', ')}; models: \`${DEFAULT_LLM}\` + \`${DEFAULT_DECISION_MODEL}\`)

${Object.entries(DECISION_TOOLS)
  .map(([n, t]) => section(n, t))
  .join('\n')}`;

export default md;

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL('../docs/agent.md', import.meta.url), md);
  console.log('wrote docs/agent.md');
}
